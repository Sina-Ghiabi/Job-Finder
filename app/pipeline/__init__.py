"""The RoleHound pipeline.

Split into focused modules, lowest-level first; each may only import from the
ones above it in this list, which is what keeps the import graph acyclic:

    errors         Exceptions raised across the pipeline.
    text           Small, dependency-free helpers for pulling values out of messy source rows.
    fetcher        Opening a page that blocks us: the four-rung fetch ladder and sitemaps.
    geo            Country / city reference tables and the lookups over them.
    rules          The content rules that decide whether one listing survives the Filter.
    language       Detecting which language a listing is written in.
    company        Working out a listing's real employer name.
    claude_screen  The optional Claude pass: final screening and legal-name lookups.
    sponsorship    Visa-sponsorship registers and matching an employer against them.
    apify          Running Apify actors and reading their datasets.
    sources_urls   Per-site search-URL builders for the direct and browser-only searches.
    sources_apis   Direct API fetchers -- one per job board with a usable public API.
    sources_norm   Normalizing each platform's raw rows into the common listing shape.
    google         Google-search query building and deepening of its results.
    preflight      Pre-run health checks over every source a search is about to use.
    healthcheck    The free, on-demand sweep of every site, API and saved pattern.
    filters        reapply_filters -- the Filter button's whole pipeline.
    search         run_search -- the Search button's whole pipeline.

This module re-exports every public name, so `from app import pipeline` and
`pipeline.whatever` keep working exactly as they did when this was one file.
"""
